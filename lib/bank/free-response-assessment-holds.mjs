export function assertNoHeldAssessmentRevisions(registry) {
  for (const key of Object.keys(registry.records)) {
    const separator = key.indexOf('#');
    if (separator < 1) continue;
    const revision = key.slice(0, separator);
    if (supersededTaskRevisions.has(revision) || reviewedPracticeHolds.has(revision)) {
      throw new Error('An assessment revision is held after editorial correction');
    }
    if (heldTaskRevisions.has(revision)) {
      throw new Error('An assessment revision is held after instructional exposure review');
    }
  }
}
